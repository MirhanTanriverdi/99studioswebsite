import { Hono } from "npm:hono";
import { cors } from "npm:hono/cors";
import { logger } from "npm:hono/logger";
import { createClient } from "npm:@supabase/supabase-js@2";
import * as kv from "./kv_store.tsx";
const app = new Hono();

// Enable logger
app.use('*', logger(console.log));

// Enable CORS for all routes and methods
app.use(
  "/*",
  cors({
    origin: "*",
    allowHeaders: ["Content-Type", "Authorization"],
    allowMethods: ["GET", "POST", "PUT", "DELETE", "OPTIONS"],
    exposeHeaders: ["Content-Length"],
    maxAge: 600,
  }),
);

// Health check endpoint
app.get("/make-server-3a4192f3/health", (c) => {
  return c.json({ status: "ok" });
});

// Appointment submission endpoint
app.post("/make-server-3a4192f3/appointments", async (c) => {
  try {
    const body = await c.req.json();
    
    // Validate required fields
    const { 
      first_name, 
      last_name, 
      phone, 
      email, 
      city, 
      placement, 
      size, 
      timeframe,
      language,
      description 
    } = body;
    
    if (!first_name || !last_name || !phone || !email || !city || !placement || !size) {
      console.log('Validation error: Missing required fields');
      return c.json({ 
        error: 'Missing required fields',
        details: 'Please ensure all required fields are filled out' 
      }, 400);
    }

    // Create Supabase client
    const supabase = createClient(
      Deno.env.get('SUPABASE_URL') ?? '',
      Deno.env.get('SUPABASE_SERVICE_ROLE_KEY') ?? '',
    );

    // Insert into contact-leads table
    const { data, error } = await supabase
      .from('contact-leads')
      .insert([
        {
          first_name,
          last_name,
          phone,
          email,
          city,
          district: body.district || null,
          placement,
          size,
          timeframe,
          language: language || 'en',
          description: description || null,
          // created_at will be auto-generated by Supabase
        }
      ])
      .select();

    if (error) {
      console.error('Supabase error while inserting appointment:', error);
      return c.json({ 
        error: 'Failed to save appointment request',
        details: error.message 
      }, 500);
    }

    console.log('Appointment saved successfully:', data);
    return c.json({ 
      success: true, 
      message: 'Appointment request submitted successfully',
      data 
    }, 201);

  } catch (error) {
    console.error('Error processing appointment submission:', error);
    return c.json({ 
      error: 'Internal server error',
      details: error instanceof Error ? error.message : 'Unknown error' 
    }, 500);
  }
});

Deno.serve(app.fetch);