/**
 * Imports each artist's tattoo work into public/work/<slug>/ as WebP.
 *
 *   node scripts/import-artist-work.mjs [sourceDir] [maxPerArtist]
 *
 * Takes up to MAX images per artist folder, skipping the Artist-photo (that is
 * the portrait, handled by import-artists.mjs) and the Archieve folder.
 *
 * Unlike the portraits, work photos stay in COLOUR — several artists tattoo in
 * colour, and desaturating would misrepresent their work.
 *
 * Emits two sizes per image: a square-cropped thumb for the grid and a full
 * version for the lightbox, plus src/app/data/artistWork.ts.
 */
import sharp from 'sharp';
import { mkdir, mkdtemp, readdir, writeFile, rm } from 'node:fs/promises';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import os from 'node:os';
import path from 'node:path';

const run_ = promisify(execFile);

/**
 * sharp's prebuilt binaries omit the HEVC decoder, so .heic from an iPhone
 * fails with a corrupt-header error. macOS ships sips, which reads HEIC
 * natively — convert to a temp PNG first and hand sharp that.
 */
const readable = async (file, tmp) => {
  if (!/\.hei[cf]$/i.test(file)) return file;
  const out = path.join(tmp, path.basename(file).replace(/\.[^.]+$/, '.png'));
  await run_('sips', ['-s', 'format', 'png', file, '--out', out]);
  return out;
};

const SRC = process.argv[2] || path.join(process.env.HOME, 'Downloads', 'Team');
const MAX = Number(process.argv[3] || 6);
const OUT = 'public/work';
const FULL_W = 1400;
const THUMB = 600;

const slug = s => s.trim().toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const isImage = f => /\.(jpe?g|png|heic|webp)$/i.test(f) && !f.startsWith('._');

const run = async () => {
  const entries = await readdir(SRC, { withFileTypes: true });
  const tmp = await mkdtemp(path.join(os.tmpdir(), 'work-heic-'));
  const manifest = {};

  for (const dir of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    if (!dir.isDirectory() || /archieve|archive/i.test(dir.name)) continue;

    const name = slug(dir.name);
    const files = (await readdir(path.join(SRC, dir.name)))
      .filter(f => isImage(f) && !/artist[-_ ]?photo/i.test(f))
      .sort()
      .slice(0, MAX);

    if (!files.length) { console.log(`${name.padEnd(10)} (is fotografi yok)`); continue; }

    await mkdir(path.join(OUT, name), { recursive: true });
    const list = [];

    for (const [i, file] of files.entries()) {
      const n = String(i + 1).padStart(2, '0');
      const src = await readable(path.join(SRC, dir.name, file), tmp);

      // .rotate() applies EXIF orientation before sharp strips the flag
      await sharp(src).rotate()
        .resize({ width: FULL_W, withoutEnlargement: true })
        .webp({ quality: 78 })
        .toFile(path.join(OUT, name, `${n}.webp`));

      // square thumb: the grid cell is aspect-square and would crop anyway
      await sharp(src).rotate()
        .resize(THUMB, THUMB, { fit: 'cover', position: 'attention' })
        .webp({ quality: 74 })
        .toFile(path.join(OUT, name, `${n}-grid.webp`));

      list.push({ url: `/work/${name}/${n}.webp`, thumb: `/work/${name}/${n}-grid.webp` });
    }

    manifest[name] = list;
    console.log(`${name.padEnd(10)} ${list.length} gorsel`);
  }

  const ts =
    `// GENERATED by scripts/import-artist-work.mjs - do not edit by hand.\n` +
    `export type WorkImage = { url: string; thumb: string };\n\n` +
    `export const artistWork: Record<string, WorkImage[]> = ${JSON.stringify(manifest, null, 2)};\n`;
  await writeFile('src/app/data/artistWork.ts', ts);

  await rm(tmp, { recursive: true, force: true });
  const total = Object.values(manifest).reduce((n, l) => n + l.length, 0);
  console.log(`\n${Object.keys(manifest).length} sanatci / ${total} gorsel -> ${OUT}/`);
};

run().catch(e => { console.error(e); process.exit(1); });
