/**
 * Imports studio photos into public/our-space/ as WebP.
 *
 *   node scripts/import-photos.mjs
 *
 * - applies EXIF orientation before stripping metadata (several source files
 *   are portrait shots flagged orientation=6; without .rotate() they publish
 *   sideways, and sharp drops the flag by default)
 * - strips all metadata, including iPhone GPS coordinates
 * - emits a full-size and a grid-size WebP per photo
 * - writes src/app/data/ourSpace.ts with real dimensions for layout
 *
 * Source filenames are messy (spaces, mixed case) and the deploy host is
 * case-sensitive, so slugs are declared explicitly below rather than derived.
 */
import sharp from 'sharp';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const SRC = '/Users/mirhantanriverdi/Desktop/99-Roots/99Roots Pictures ';
const OUT = 'public/our-space';

// file -> { slug, alt, rotate }  — `rotate` is extra manual rotation in degrees
// for files that are visually sideways but carry no EXIF orientation flag.
const PHOTOS = [
  { file: 'Heroall-station.JPG',           slug: 'tattoo-floor-wide',   alt: 'The main tattoo floor at 99 Roots Studio, stations lined up under hexagon lighting' },
  { file: 'waitingGood.JPG',               slug: 'lounge-neon-sign',    alt: 'The 99 Roots neon sign above the lounge sofa, beside the clothing rack and jewellery cabinet' },
  { file: 'Full Station area.JPG',         slug: 'tattoo-floor-stations', alt: 'Tattoo stations with adjustable beds, mirrors, lamps and equipment carts' },
  { file: 'McLoving.JPG',                  slug: 'lounge-seating',      alt: 'Lounge seating area with bouclé armchairs, patterned artwork and the studio dog resting by the screen' },
  { file: 'FullSizeRender.JPG',            slug: 'tattoo-floor-tall',   alt: 'The tattoo floor looking toward the hexagon light array, with plants framing the entrance' },
  { file: 'McLovin-WaitingRoom.JPG',       slug: 'lounge-corridor',     alt: 'The lounge looking down toward the neon sign, with the studio dog lying by the slatted divider' },
  { file: 'Full Waiting Area.JPG',         slug: 'lounge-neon-wide',    alt: 'Wide view of the lounge with the neon sign, clothing rack and seating' },
  { file: 'McLovin-waiting-otherside.JPG', slug: 'lounge-seating-two',  alt: 'The lounge seating from the opposite side, showing the artwork niche and screen' },
  { file: 'FullSizeRender 2.JPG',          slug: 'tattoo-floor-open',   alt: 'The open tattoo floor at 99 Roots Studio, stations either side of a clear walkway' },
];

const FULL_W = 2000;
const GRID_W = 900;

const run = async () => {
  await mkdir(OUT, { recursive: true });
  await mkdir('src/app/data', { recursive: true });
  const manifest = [];

  for (const { file, slug, alt, rotate = 0 } of PHOTOS) {
    const src = path.join(SRC, file);
    const meta = await sharp(src).metadata();

    // .rotate() with no argument applies the EXIF orientation; an explicit
    // angle is used for files whose pixels are sideways with no flag set.
    const base = () => (rotate ? sharp(src).rotate(rotate) : sharp(src).rotate());

    const full = await base()
      .resize({ width: FULL_W, withoutEnlargement: true })
      .webp({ quality: 78 })
      .toFile(path.join(OUT, `${slug}.webp`));

    await base()
      .resize({ width: GRID_W, withoutEnlargement: true })
      .webp({ quality: 74 })
      .toFile(path.join(OUT, `${slug}-grid.webp`));

    manifest.push({ slug, alt, width: full.width, height: full.height });
    console.log(
      `${slug.padEnd(20)} ${meta.width}x${meta.height} orient=${meta.orientation ?? 1}` +
      ` -> ${full.width}x${full.height}  ${(full.size / 1024).toFixed(0)}KB`
    );
  }

  const ts =
    `// GENERATED by scripts/import-photos.mjs - do not edit by hand.\n` +
    `export type SpacePhoto = {\n  slug: string;\n  alt: string;\n  width: number;\n  height: number;\n};\n\n` +
    `export const spacePhotos: SpacePhoto[] = ${JSON.stringify(manifest, null, 2)};\n`;
  await writeFile('src/app/data/ourSpace.ts', ts);
  console.log(`\n${manifest.length} photos -> ${OUT}/  + src/app/data/ourSpace.ts`);
};

run().catch(e => {
  console.error(e);
  process.exit(1);
});
